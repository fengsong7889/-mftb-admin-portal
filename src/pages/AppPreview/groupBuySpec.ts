/* ─── localStorage 读写（按面板分 key；版本号变更时自动失效该面板旧缓存） ─── */

function storageKey(panel: SpecPanelKey) {
  if (panel === 'preferred') return 'app-preview:preferred-specs'
  if (panel === 'groupPage') return 'app-preview:group-page-specs'
  if (panel === 'filter') return 'app-preview:filter-specs'
  if (panel === 'deliveryPage') return 'app-preview:delivery-page-specs'
  if (panel === 'searchDelivery') return 'app-preview:search-delivery-specs'
  if (panel === 'searchGroup') return 'app-preview:search-group-specs'
  return panel === 'groupBuy' ? 'app-preview:group-buy-specs' : 'app-preview:delivery-specs'
}

export function loadSpecs(panel: SpecPanelKey): SpecEntry[] {
  const target = SPEC_PANELS.find((p) => p.key === panel) ?? SPEC_PANELS[0]
  try {
    const key = storageKey(panel)
    const raw = localStorage.getItem(key)
    const verRaw = localStorage.getItem(key + ':v')
    if (!raw || verRaw !== String(target.version)) return target.defaults
    const saved: SpecEntry[] = JSON.parse(raw)
    return saved.length > 0 ? saved : target.defaults
  } catch {
    return target.defaults
  }
}

export function saveSpecs(panel: SpecPanelKey, specs: SpecEntry[]) {
  const target = SPEC_PANELS.find((p) => p.key === panel) ?? SPEC_PANELS[0]
  const key = storageKey(panel)
  localStorage.setItem(key, JSON.stringify(specs))
  localStorage.setItem(key + ':v', String(target.version))
}

export function resetSpecs(panel: SpecPanelKey) {
  localStorage.removeItem(storageKey(panel))
}
