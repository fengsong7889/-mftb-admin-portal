/* ─── 字段规范接口 ─── */
export interface SpecEntry {
  id: number
  label: string
  desc: string
  source: string
  /** 展示品牌：both=双品牌（缺省）、bee=仅閃蜂、mfood=仅MFOOD */
  brand?: 'both' | 'bee' | 'mfood'
  /** 重点提示（醒目色展示，如旧系统遗留/仅某品牌有等注意项） */
  note?: string
}

/** 说明面板 key */
export type SpecPanelKey = 'groupBuy' | 'delivery'

export interface SpecPanel {
  key: SpecPanelKey
  /** 面板 Tab 文案 */
  label: string
  defaults: SpecEntry[]
  /** localStorage 版本号（变更时自动失效该面板旧缓存） */
  version: number
}

