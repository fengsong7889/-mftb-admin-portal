/**
 * 瀑布流卡片 · 字段规范（唯一真源，多面板）
 *
 * 本文件是壳外说明表格的唯一数据源，同时驱动：
 * - 手机壳内的 SpecField 高亮联动（表格行 hover → 卡片对应字段流光描边）
 * - 壳外说明表格的渲染（index.tsx 面板，可按面板 Tab 切换）
 *
 * 面板：groupBuy=团购瀑布流（GroupBuyFeedCard）；delivery=外卖瀑布流（DeliveryStoreCard / MfoodDeliveryStoreCard）。
 * 增删字段：修改对应面板数组 + 在卡片 JSX 里加/去 <SpecField id={N}> 包裹。
 * 编辑说明：表格双击可原地编辑，按面板分 key 存 localStorage 覆盖默认值。
 */

/* ─── 字段规范接口 ─── */
export interface SpecEntry {
  id: number
  label: string
  desc: string
  source: string
  /** 展示品牌：both=双品牌（缺省）、bee=仅閃蜂、mfood=仅MFOOD */
  brand?: 'both' | 'bee' | 'mfood'
  /** 重点提示（醒目色展示，如旧系统遗留/仅某品牌有等注意项） */
  note?: string
  /** 外部详情链接（渲染为可点击跳转按钮，新标签页打开）；缺省不渲染 */
  link?: string
  /**
   * 最近一轮口径调整标记（壳外说明表专用，不进入手机壳）：
   * date=调整日期（YYYY-MM-DD），text=本轮改了什么（一句话说清，供开发/测试/设计快速定位变更面与回归范围）。
   * 渲染为名称列的「🆕 日期」徽标 + 说明列末尾的「本次調整」蓝底行；
   * desc 正文是累计真值（新口径写进正文），changed 只标最近一轮——下一轮直接覆盖，历史靠 git 追。
   */
  changed?: { date: string; text: string }
  /**
   * 口径作废标记（仅作用于 note）：true 时该 note 原文不删、整条用删除线画掉并灰化。
   * 取【画掉而非删除】：开发/测试/设计需要看见“这条规则曾经存在、现已下线”，直接删文本会丢历史口径。
   * 与 changed 配套使用：作废哪一轮、为什么作废，写进 changed。
   */
  deprecated?: boolean
}

/** 说明面板 key（deliveryPage=美食外卖频道页，与首页外卖瀑布流共用 DELIVERY_SPECS 内容；searchDelivery/searchGroup=首页搜索结果瀑布流三级：外卖/团购；searchDeliveryPage/searchGroupPage=频道内搜索结果瀑布流） */
export type SpecPanelKey = 'groupBuy' | 'delivery' | 'preferred' | 'groupPage' | 'filter' | 'deliveryPage' | 'searchDelivery' | 'searchGroup' | 'searchDeliveryPage' | 'searchGroupPage' | 'deliveryFilter'

export interface SpecPanel {
  key: SpecPanelKey
  /** 菜单分类（说明 Tab 分组）：首页 / 特惠团购页 */
  group: string
  /** 面板 Tab 文案 */
  label: string
  defaults: SpecEntry[]
  /** localStorage 版本号（变更时自动失效该面板旧缓存） */
  version: number
  /** 高亮锚点作用域：卡片 SpecField 的 panel 值；缺省=key（「推荐」与首页团购共用 groupBuy 锚点） */
  anchor?: SpecPanelKey
  /** 面板标题覆盖（h3）：缺省=「{group} · {label} · 展示字段及标签说明」 */
  title?: string
  /** 隐藏面板：不在二级 Tab 轨道展示，仅由三级切换器（如搜索结果瀑布流的 外卖/团购）寻址 */
  hidden?: boolean
  /** 隐藏面板激活时，二级轨道应高亮的父 Tab（如搜索结果·团购 → 搜索结果瀑布流） */
  tabAlias?: SpecPanelKey
}

