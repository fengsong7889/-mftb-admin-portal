/**
 * 瀑布流卡片 · 字段规范（唯一真源，多面板）
 *
 * 本文件是壳外说明表格的唯一数据源，同时驱动：
 * - 手机壳内的 SpecField 高亮联动（表格行 hover → 卡片对应字段流光描边）
 * - 壳外说明表格的渲染（index.tsx 面板，可按面板 Tab 切换）
 *
 * 面板：groupBuy=团购瀑布流（GroupBuyFeedCard）；delivery=外卖瀑布流（DeliveryStoreCard / MfoodDeliveryStoreCard）。
 * 增删字段：修改对应面板数组 + 在卡片 JSX 里加/去 <SpecField id={N}> 包裹。
 * 编辑说明：表格双击可原地编辑，按面板分 key 存 localStorage 覆盖默认值。
 */

/* ─── 字段规范接口 ─── */
export interface SpecEntry {
  id: number
  label: string
  desc: string
  source: string
  /** 展示品牌：both=双品牌（缺省）、bee=仅閃蜂、mfood=仅MFOOD */
  brand?: 'both' | 'bee' | 'mfood'
  /** 重点提示（醒目色展示，如旧系统遗留/仅某品牌有等注意项） */
  note?: string
}

/** 说明面板 key（deliveryPage=美食外卖频道页，与首页外卖瀑布流共用 DELIVERY_SPECS 内容；searchDelivery/searchGroup=首页搜索结果瀑布流三级：外卖/团购） */
export type SpecPanelKey = 'groupBuy' | 'delivery' | 'preferred' | 'groupPage' | 'filter' | 'deliveryPage' | 'searchDelivery' | 'searchGroup'

export interface SpecPanel {
  key: SpecPanelKey
  /** 菜单分类（说明 Tab 分组）：首页 / 特惠团购页 */
  group: string
  /** 面板 Tab 文案 */
  label: string
  defaults: SpecEntry[]
  /** localStorage 版本号（变更时自动失效该面板旧缓存） */
  version: number
  /** 高亮锚点作用域：卡片 SpecField 的 panel 值；缺省=key（「推荐」与首页团购共用 groupBuy 锚点） */
  anchor?: SpecPanelKey
  /** 面板标题覆盖（h3）：缺省=「{group} · {label} · 展示字段及标签说明」 */
  title?: string
  /** 隐藏面板：不在二级 Tab 轨道展示，仅由三级切换器（如搜索结果瀑布流的 外卖/团购）寻址 */
  hidden?: boolean
  /** 隐藏面板激活时，二级轨道应高亮的父 Tab（如搜索结果·团购 → 搜索结果瀑布流） */
  tabAlias?: SpecPanelKey
}

