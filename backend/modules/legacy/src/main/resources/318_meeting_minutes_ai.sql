-- 318: 会议纪要自然语言录入：个人笔记与可恢复、可计量的 AI 提取请求。
-- 本资源为执行真值，backend/sql/ 同名文件为参考副本。仅新增，不改正式纪要及历史快照。
CREATE TABLE IF NOT EXISTS biz_meeting_minutes_note (
    id BIGINT NOT NULL AUTO_INCREMENT,
    booking_id BIGINT NOT NULL,
    owner_user_id BIGINT NOT NULL,
    raw_text MEDIUMTEXT NOT NULL,
    mentions_json JSON NOT NULL,
    version INT NOT NULL DEFAULT 1,
    content_hash CHAR(64) NOT NULL,
    last_request_key VARCHAR(64) NOT NULL,
    last_request_hash CHAR(64) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    created_at DATETIME(3) NOT NULL COMMENT 'UTC',
    updated_by VARCHAR(64) NOT NULL,
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_minutes_note_owner (booking_id, owner_user_id),
    KEY idx_minutes_note_user (owner_user_id, updated_at),
    CONSTRAINT fk_minutes_note_booking FOREIGN KEY (booking_id) REFERENCES biz_meeting_booking(id),
    CONSTRAINT fk_minutes_note_owner FOREIGN KEY (owner_user_id) REFERENCES sys_user(id),
    CONSTRAINT ck_minutes_note_version CHECK (version >= 1),
    CONSTRAINT ck_minutes_note_length CHECK (CHAR_LENGTH(raw_text) <= 20000),
    CONSTRAINT ck_minutes_note_mentions CHECK (JSON_TYPE(mentions_json) = 'ARRAY')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='个人会议笔记，不进入发布及通知';

CREATE TABLE IF NOT EXISTS biz_meeting_minutes_ai_extraction (
    id BIGINT NOT NULL AUTO_INCREMENT,
    booking_id BIGINT NOT NULL,
    note_id BIGINT NOT NULL,
    operator_user_id BIGINT NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    note_version INT NOT NULL,
    source_hash CHAR(64) NOT NULL,
    source_snapshot JSON NULL COMMENT '提取原文和人员标记快照，7天后清空',
    base_minutes_id BIGINT NULL,
    base_minutes_version INT NULL,
    meeting_date DATE NOT NULL,
    timezone VARCHAR(64) NOT NULL,
    status TINYINT NOT NULL DEFAULT 0 COMMENT '0处理中 1成功 2失败 3结果未知 4结果过期',
    active_operator_id BIGINT GENERATED ALWAYS AS (CASE WHEN status = 0 THEN operator_user_id ELSE NULL END) STORED,
    prompt_version VARCHAR(32) NOT NULL,
    schema_version INT NOT NULL DEFAULT 1,
    model_key VARCHAR(128) NULL,
    result_json JSON NULL,
    error_code VARCHAR(64) NULL,
    billing_status TINYINT NOT NULL DEFAULT 0 COMMENT '0未预占 1已预占 2已结算 3待核对 4已释放',
    billing_context_json JSON NULL COMMENT '预占期别、价格及币种快照，不含供应商凭据',
    usage_json JSON NULL COMMENT '只存用量，不存供应商原始响应',
    applied_minutes_id BIGINT NULL,
    applied_minutes_version INT NULL,
    applied_keys_json JSON NULL,
    applied_at DATETIME(3) NULL COMMENT 'UTC',
    started_at DATETIME(3) NOT NULL COMMENT 'UTC',
    finished_at DATETIME(3) NULL COMMENT 'UTC',
    result_expires_at DATETIME(3) NOT NULL COMMENT 'UTC',
    metadata_expires_at DATETIME(3) NOT NULL COMMENT 'UTC',
    created_by VARCHAR(64) NOT NULL,
    created_at DATETIME(3) NOT NULL COMMENT 'UTC',
    updated_by VARCHAR(64) NOT NULL,
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC',
    PRIMARY KEY (id),
    UNIQUE KEY uk_minutes_ai_request (operator_user_id, request_key),
    UNIQUE KEY uk_minutes_ai_running (active_operator_id),
    KEY idx_minutes_ai_recent (booking_id, operator_user_id, created_at),
    KEY idx_minutes_ai_rate (operator_user_id, created_at),
    KEY idx_minutes_ai_recovery (status, updated_at),
    KEY idx_minutes_ai_billing (billing_status, updated_at),
    KEY idx_minutes_ai_expiry (result_expires_at, metadata_expires_at),
    CONSTRAINT fk_minutes_ai_booking FOREIGN KEY (booking_id) REFERENCES biz_meeting_booking(id),
    CONSTRAINT fk_minutes_ai_note FOREIGN KEY (note_id) REFERENCES biz_meeting_minutes_note(id),
    CONSTRAINT fk_minutes_ai_operator FOREIGN KEY (operator_user_id) REFERENCES sys_user(id),
    CONSTRAINT fk_minutes_ai_base FOREIGN KEY (base_minutes_id) REFERENCES biz_meeting_minutes(id),
    CONSTRAINT fk_minutes_ai_applied FOREIGN KEY (applied_minutes_id) REFERENCES biz_meeting_minutes(id),
    CONSTRAINT ck_minutes_ai_status CHECK (status IN (0,1,2,3,4)),
    CONSTRAINT ck_minutes_ai_billing CHECK (billing_status IN (0,1,2,3,4)),
    CONSTRAINT ck_minutes_ai_versions CHECK (note_version >= 1 AND schema_version = 1 AND (base_minutes_version IS NULL OR base_minutes_version >= 0)),
    CONSTRAINT ck_minutes_ai_expiry CHECK (metadata_expires_at >= result_expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin COMMENT='会议纪要AI提取与恢复，永不自动发布';
