-- ============================================================================
-- 阶段 6 补丁：绩效建议表的预算占用列过窄
-- 版本：v2.3
-- 背景：budget_used_ratio 原本 DECIMAL(5,2)，最大只能存 999.99。
--       深度测试实测：预算上限 5 分、该部门实际产出 214.78 分时，占用为 4295.60，
--       聚合绩效建议在回写预算标记处直接 Data truncation: Out of range，
--       整个「聚合 → 复核 → 推送」链路 100% 不可用。
--       超限倍数天然可能很大（预算设得过小、跨部门汇总、历史数据），因此扩到 DECIMAL(9,2)。
-- 幂等：MODIFY COLUMN 可重复执行；核验用 information_schema 读实际列类型。
-- ============================================================================

ALTER TABLE rdm_hr_suggestion
    MODIFY COLUMN budget_used_ratio DECIMAL(9,2) NOT NULL DEFAULT 0.00 COMMENT '所屬部門預算占用百分比（可遠超 100）';
