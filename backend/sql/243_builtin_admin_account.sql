-- 步骤 2：把除系统账号以外的所有超管降级为普通账号
--   只改 sys_user.role，不动姓名/部门/工号 —— 它仍是可用员工账号，
--   后续权限由 HR 在界面上按角色（function_roles）与部门授权正常授予。
-- ------------------------------------------------------------
-- UPDATE sys_user
